/**
 * CSS Variables Generator
 * 
 * This utility generates CSS variables from the design tokens.
 * It converts the JavaScript objects into CSS custom properties.
 */

import colors from '../tokens/colors';
import typography from '../tokens/typography';
import spacing from '../tokens/spacing';
import shadows from '../tokens/shadows';
import borders from '../tokens/borders';
import animations from '../tokens/animations';
import breakpoints from '../tokens/breakpoints';

/**
 * Flatten a nested object into a flat object with kebab-case keys.
 * 
 * @param {Object} obj - The object to flatten.
 * @param {string} prefix - The prefix to add to the keys.
 * @returns {Object} - The flattened object.
 * 
 * @example
 * // Returns { 'color-primary': '#0A2647', 'color-secondary': '#144272' }
 * flattenObject({ color: { primary: '#0A2647', secondary: '#144272' } });
 */
export function flattenObject(obj, prefix = '') {
  return Object.keys(obj).reduce((acc, key) => {
    const prefixedKey = prefix ? `${prefix}-${key}` : key;
    
    if (typeof obj[key] === 'object' && obj[key] !== null && !Array.isArray(obj[key])) {
      Object.assign(acc, flattenObject(obj[key], prefixedKey));
    } else {
      acc[prefixedKey] = obj[key];
    }
    
    return acc;
  }, {});
}

/**
 * Convert a camelCase or PascalCase string to kebab-case.
 * 
 * @param {string} str - The string to convert.
 * @returns {string} - The kebab-case string.
 * 
 * @example
 * // Returns 'primary-color'
 * toKebabCase('primaryColor');
 */
export function toKebabCase(str) {
  return str
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z])(?=[a-z])/g, '$1-$2')
    .toLowerCase();
}

/**
 * Generate CSS variables from the design tokens.
 * 
 * @returns {string} - The CSS variables as a string.
 */
export function generateCSSVariables() {
  // Prepare the tokens
  const colorTokens = flattenObject(colors.semantic, 'color');
  const typographyTokens = {
    'font-family-primary': typography.fontFamilies.primary,
    'font-family-code': typography.fontFamilies.code,
    ...flattenObject(typography.fontSizes, 'font-size'),
    ...flattenObject(typography.fontWeights, 'font-weight'),
    ...flattenObject(typography.lineHeights, 'line-height'),
    ...flattenObject(typography.letterSpacing, 'letter-spacing'),
  };
  const spacingTokens = flattenObject(spacing, 'spacing');
  const shadowTokens = flattenObject(shadows, 'shadow');
  const borderTokens = {
    ...flattenObject(borders.width, 'border-width'),
    ...flattenObject(borders.style, 'border-style'),
    ...flattenObject(borders.radius, 'border-radius'),
  };
  const animationTokens = {
    ...flattenObject(animations.durations, 'duration'),
    ...flattenObject(animations.easings, 'easing'),
    ...flattenObject(animations.transition, 'transition'),
  };
  const breakpointTokens = flattenObject(breakpoints.values, 'breakpoint');
  
  // Combine all tokens
  const allTokens = {
    ...colorTokens,
    ...typographyTokens,
    ...spacingTokens,
    ...shadowTokens,
    ...borderTokens,
    ...animationTokens,
    ...breakpointTokens,
  };
  
  // Generate CSS variables
  let cssVariables = ':root {\n';
  
  Object.entries(allTokens).forEach(([key, value]) => {
    cssVariables += `  --${toKebabCase(key)}: ${value};\n`;
  });
  
  cssVariables += '}\n\n';
  
  // Add color palette
  cssVariables += '/* Color Palette */\n';
  Object.entries(colors.colorPalette).forEach(([colorName, shades]) => {
    Object.entries(shades).forEach(([shade, value]) => {
      cssVariables += `  --color-${toKebabCase(colorName)}-${shade}: ${value};\n`;
    });
  });
  
  // Add keyframes
  cssVariables += '\n/* Keyframes */\n';
  Object.values(animations.keyframes).forEach((keyframe) => {
    cssVariables += keyframe + '\n';
  });
  
  return cssVariables;
}

